package tax.black.core.domain;

import static org.assertj.core.api.Assertions.assertThat;
import static tax.black.core.domain.AssertUtils.bigDecimalCompareTo;

public class DebtAsserts {

    /**
     * Asserts that the entity has all properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertDebtAllPropertiesEquals(Debt expected, Debt actual) {
        assertDebtAutoGeneratedPropertiesEquals(expected, actual);
        assertDebtAllUpdatablePropertiesEquals(expected, actual);
    }

    /**
     * Asserts that the entity has all updatable properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertDebtAllUpdatablePropertiesEquals(Debt expected, Debt actual) {
        assertDebtUpdatableFieldsEquals(expected, actual);
        assertDebtUpdatableRelationshipsEquals(expected, actual);
    }

    /**
     * Asserts that the entity has all the auto generated properties (fields/relationships) set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertDebtAutoGeneratedPropertiesEquals(Debt expected, Debt actual) {
        assertThat(actual)
            .as("Verify Debt auto generated properties")
            .satisfies(a -> assertThat(a.getId()).as("check id").isEqualTo(expected.getId()));
    }

    /**
     * Asserts that the entity has all the updatable fields set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertDebtUpdatableFieldsEquals(Debt expected, Debt actual) {
        assertThat(actual)
            .as("Verify Debt relevant properties")
            .satisfies(a -> assertThat(a.getTenantId()).as("check tenantId").isEqualTo(expected.getTenantId()))
            .satisfies(a -> assertThat(a.getCreditor()).as("check creditor").isEqualTo(expected.getCreditor()))
            .satisfies(a -> assertThat(a.getKind()).as("check kind").isEqualTo(expected.getKind()))
            .satisfies(a ->
                assertThat(a.getStartBalance())
                    .as("check startBalance")
                    .usingComparator(bigDecimalCompareTo)
                    .isEqualTo(expected.getStartBalance())
            )
            .satisfies(a ->
                assertThat(a.getBalance()).as("check balance").usingComparator(bigDecimalCompareTo).isEqualTo(expected.getBalance())
            )
            .satisfies(a ->
                assertThat(a.getInterestRate())
                    .as("check interestRate")
                    .usingComparator(bigDecimalCompareTo)
                    .isEqualTo(expected.getInterestRate())
            )
            .satisfies(a ->
                assertThat(a.getMinimumPayment())
                    .as("check minimumPayment")
                    .usingComparator(bigDecimalCompareTo)
                    .isEqualTo(expected.getMinimumPayment())
            )
            .satisfies(a -> assertThat(a.getStatus()).as("check status").isEqualTo(expected.getStatus()))
            .satisfies(a -> assertThat(a.getClearedDate()).as("check clearedDate").isEqualTo(expected.getClearedDate()));
    }

    /**
     * Asserts that the entity has all the updatable relationships set.
     *
     * @param expected the expected entity
     * @param actual the actual entity
     */
    public static void assertDebtUpdatableRelationshipsEquals(Debt expected, Debt actual) {
        assertThat(actual)
            .as("Verify Debt relationships")
            .satisfies(a -> assertThat(a.getMember()).as("check member").isEqualTo(expected.getMember()));
    }
}
